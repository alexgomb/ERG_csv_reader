class Translator:
    """Lightweight live-switchable EN/ES translator."""

    def __init__(self, language: str = "en") -> None:
        self._language = language if language in SUPPORTED_LANGUAGES else "en"

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        if language in SUPPORTED_LANGUAGES:
            self._language = language

    def tr(self, key: str, **kwargs: object) -> str:
        table = TRANSLATIONS.get(self._language, TRANSLATIONS["en"])
        template = table.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            return template.format(**kwargs)
        return template
